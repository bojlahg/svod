/** Row shapes. Kept in lockstep with src/db/migrations/*.sql by hand. */

export type Plan = "free" | "pro" | "team" | "admin";
export type Visibility = "private" | "link" | "public";
export type License = "nc" | "mit" | "proprietary";
export type SourceKind = "image" | "text" | "url" | "file" | "site" | "repo";
export type SourceStatus = "queued" | "processing" | "ready" | "failed" | "rejected";
export type NoteKind = "fact" | "rule" | "layout" | "example" | "pitfall";
export type NoteStatus = "active" | "pending" | "superseded" | "rejected";
export type GrantRole = "viewer" | "contributor";

export interface User {
  id: string;
  name: string | null;
  email: string;
  image: string | null;
  plan: Plan;
  handle: string | null;
  /** Set when the plan was paid for (balance checkout or an approved request).
      Null on a hand-set plan, which does not expire. See effectivePlan. */
  paid_until: Date | null;
}

export interface Brain {
  id: string;
  owner_id: string;
  slug: string;
  title: string;
  goal: string | null;
  color: string;
  /** Catalogue field — see src/lib/topics.ts. Free text; unknown reads as "other". */
  topic: string;
  /** Groups this brain under another. One level only; see 0006_families.sql. */
  parent_id: string | null;
  visibility: Visibility;
  license: License;
  score: number | null;
  score_at: Date | null;
  /** The same exam graded against the model's own knowledge, no brain (0092).
   *  Null until a sitting has measured both halves. */
  score_closed: number | null;
  /** score - score_closed, generated by the database so the difference can
   *  never disagree with the two numbers it came from. This is what the
   *  catalogue sorts on and what a brain page leads with: a corpus that only
   *  repeats what the model already knew has a delta near zero however high
   *  its score. */
  delta: number | null;
  review_required: boolean;
  /** Readers' agents may propose notes. They always land pending; see 0067. */
  contributions: boolean;
  /** Storage key of the one upload the owner made public as a cover; see 0068. */
  cover_key: string | null;
  /** What this brain is: a knowledge pack, or a reproducible style. See 0069 —
   *  it selects the extraction prompt and the exam, not just a label. */
  kind: "knowledge" | "style";
  /** SVOD stage 4: stable external project ID. NULL = general (thematic) base,
   *  NOT NULL = private project base. Keyed by this, never display title.
   *  Global unique where not null (0095), immutable after creation. */
  project_id: string | null;
  note_count: number;
  source_count: number;
  /** 0 means free. Access to a paid brain is bought once, from balance. */
  price_cents: number;
  sales_count: number;
  created_at: Date;
  updated_at: Date;
  /** Local tools this brain's knowledge is executed with (0087). Owner-authored
   *  and untrusted — always read through lib/brain-tools.ts parseTools. */
  tools?: unknown;

}

export type LedgerKind =
  | "topup"
  | "purchase"
  | "earning"
  | "payout"
  | "refund"
  | "adjustment"
  | "plan"
  // Per-image use of a style brain: the buyer's debit. The artist's side
  // is an "earning", the same kind a sale pays them under, so one payout
  // query still sees everything they are owed.
  | "generation";

export interface LedgerEntry {
  id: string;
  user_id: string;
  /** Signed: positive credits, negative debits. */
  amount_cents: number;
  kind: LedgerKind;
  brain_id: string | null;
  purchase_id: string | null;
  external_ref: string | null;
  note: string | null;
  created_at: Date;
}

export interface Purchase {
  id: string;
  brain_id: string;
  buyer_id: string;
  seller_id: string;
  price_cents: number;
  seller_cents: number;
  created_at: Date;
}

export interface Source {
  id: string;
  brain_id: string;
  kind: SourceKind;
  storage_key: string | null;
  original_name: string | null;
  mime: string | null;
  bytes: number | null;
  url: string | null;
  status: SourceStatus;
  reject_reason: string | null;
  findings: Finding[] | null;
  /** Owner said the scan hits are documentation examples — let them through. */
  scan_waived: boolean;
  error: string | null;
  note_count: number;
  cost_cents: number | null;
  /** What the cost was made of. Output bills about five times input, and on
   *  this corpus it is two thirds of the extraction bill — see 0077. */
  input_tokens: number | null;
  output_tokens: number | null;
  /** Cached extraction so a queue retry skips the paid step; see 0011. */
  extract_payload: unknown;
  /** Set by the maintenance refresh when the page's text moved; compared
   *  against processed_at to tell a refresh re-ingest from a first read. */
  changed_at: Date | null;
  created_at: Date;
  processed_at: Date | null;
}

export interface Note {
  id: string;
  brain_id: string;
  source_id: string | null;
  /** SVOD stage 3: optional folder; NULL = base root. Same-base enforced. */
  folder_id: string | null;
  title: string;
  body: string;
  category: string | null;
  kind: NoteKind;
  confidence: number;
  author: "ingest" | "human" | "agent" | "consolidated";
  agent_client: string | null;
  /** The reader whose agent proposed this note. Null when the owner wrote it. */
  proposed_by: string | null;
  status: NoteStatus;
  superseded_by: string | null;
  /** Feedback-driven ranking multiplier, clamped 0.5-2.0; see note-weight.ts. */
  weight: number;
  created_at: Date;
  /** SVOD stage 4: last-updated timestamp, auto-touched on update (0095). */
  updated_at: Date;
  /** Monotonic integer revision, bumped on every UPDATE via trigger (0095).
   *  Authority for stale detection (timestamps lose precision in node-pg). */
  revision: number;
  /** SVOD stage 4: edit-proposal target (active note being edited).
   *  NULL = new-note proposal / ordinary note. Same-brain enforced natively
   *  via composite FK (brain_id, target_note_id). */
  target_note_id: string | null;
  /** Target.revision at proposal time, for exact stale-target detection. */
  target_revision: number | null;
  /** Source token that created this note/proposal. Survives soft revocation
   *  (FK SET NULL only on hard delete); revoked rows still join for display. */
  token_id: string | null;
  /** Token that last updated a project note (direct-write). Same survival. */
  updated_token_id: string | null;
}

export interface Folder {
  id: string;
  brain_id: string;
  parent_id: string | null;
  name: string;
  created_at: Date;
  updated_at: Date;
}

export interface Chunk {
  id: string;
  brain_id: string;
  note_id: string;
  content: string;
  token_count: number;
}

export interface Check {
  id: string;
  brain_id: string;
  category: string;
  question: string;
  expect: string;
  weight: number;
  /** generated = from the goal; manual = owner-written; usage = zero-result
   *  searches (exam-time); search_gap = clustered weak searches (0042). */
  origin: "generated" | "manual" | "usage" | "search_gap";
  /** negative = out-of-scope probe: passing means the brain has NO answer. */
  kind: "positive" | "negative";
  enabled: boolean;
  /** When the question was written. An exam is rewritten once most of the
   *  brain's notes postdate it — see examOutgrown. */
  created_at: Date;
  /** The control arm (0092): did the judge pass this question when shown the
   *  model's own unaided answer instead of the brain's passages? Null until
   *  asked. Cached here rather than recomputed per sitting — a model's own
   *  knowledge does not move between two sittings, the question set does. */
  closed_passed: boolean | null;
  closed_at: Date | null;
  /** Which model was asked. When MODEL_JUDGE changes the cached verdict is a
   *  fact about a different model, and the run re-asks rather than subtracting
   *  two models from each other. */
  closed_model: string | null;
}

/** A failed "material missing" check surfaced to the owner (0043). */
export interface GapSuggestion {
  id: string;
  brain_id: string;
  check_id: string | null;
  question: string;
  status: "pending" | "accepted" | "dismissed";
  created_at: Date;
  resolved_at: Date | null;
}

export interface CheckRun {
  id: string;
  brain_id: string;
  score: number | null;
  /** The closed-book half of this sitting, over the same live checks (0092). */
  score_closed: number | null;
  model: string | null;
  cost_cents: number | null;
  /** full = a real sitting; mini = the cheap single-vote probe after a
   *  content refresh (0047) — it never moves the brain's official score. */
  kind: "full" | "mini";
  status: "running" | "done" | "failed";
  error: string | null;
  started_at: Date;
  finished_at: Date | null;
}

export interface Grant {
  id: string;
  brain_id: string;
  email: string;
  role: GrantRole;
  accepted_by: string | null;
  invited_by: string;
  invited_at: Date;
}

export interface McpToken {
  id: string;
  user_id: string;
  token_hash: string;
  prefix: string;
  name: string | null;
  last_used_at: Date | null;
  revoked_at: Date | null;
  created_at: Date;
  /** SVOD stage 4: separate default-off project-creation capability (0095). */
  can_create_project: boolean;
}

/** SVOD stage 4 per-token per-brain grant (0095). Default deny: no row = no access. */
export type TokenCapability = "read" | "propose" | "write";

export interface McpTokenScope {
  id: string;
  token_id: string;
  brain_id: string;
  capability: TokenCapability;
  granted_by: string | null;
  granted_at: Date;
}

/** A masked secret-scan hit. `sample` is already redacted — never store raw. */
export interface Finding {
  rule: string;
  label: string;
  sample: string;
  line?: number;
}
